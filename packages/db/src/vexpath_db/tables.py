# Tenant tables
#
# Every one of these carries org_id, and row-level security is what keeps one
# organisation's rows away from another's. The column is not a convenience for
# queries: it is the thing the policies compare against, so a table without it
# cannot be protected.
# ---------------------------------------------------------------------------

#: Tenant tables, in dependency order. The migration enables row-level
#: security on each, and a test asserts that every table listed here has both
#: an org_id column and a policy, so adding a table without protecting it
#: fails rather than quietly leaking.
