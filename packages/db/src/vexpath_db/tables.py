#: The Postgres session setting a request puts its organisation in. Every
#: policy reads this; nothing else decides which rows are visible.
ORG_SETTING = "vexpath.org_id"

#: Session setting that opens the public read path: the report pages of a
#: project whose visibility is 'public', and nothing else. Separate from the
#: org setting so a public page cannot accidentally be served with a tenant's
#: context attached.
PUBLIC_SETTING = "vexpath.public"

#: The non-privileged role the application runs as. Policies do not apply to a
#: superuser or to a table's owner, so connecting as the owner would make
#: row-level security decorative.
APP_ROLE = "vexpath_app"


