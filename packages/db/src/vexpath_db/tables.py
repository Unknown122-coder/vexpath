#: Naming convention so that autogenerated migrations produce stable, readable
#: constraint names instead of database-assigned ones.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)

#: Portable JSON column: JSONB on Postgres, plain JSON elsewhere (SQLite in
#: unit tests), so schema tests do not need a database server.
_Json = JSON().with_variant(JSONB(), "postgresql")
_StringArray = JSON().with_variant(ARRAY(Text()), "postgresql")


def _check(column: str, enum_cls: type[StrEnum], name: str) -> CheckConstraint:
    """Constrain a text column to the values of a Python enum."""
    allowed = ", ".join(f"'{member.value}'" for member in enum_cls)
    return CheckConstraint(f"{column} IN ({allowed})", name=name)


