"""SQLAlchemy Core table definitions.

Two families of table, and the difference decides how every query against them
is written.

**Global tables** hold the advisory corpus and the call-graph cache index. They
are world-readable, written only by the advisory pipeline, and belong to no
tenant.

**Tenant tables** hold what one organisation uploaded, and every one of them
carries ``org_id``. Isolation is enforced by Postgres row-level security
rather than by remembering to add a ``WHERE`` clause, because a filter that
has to be remembered is a filter that will one day be forgotten, and the
consequence is one customer reading another's source inventory.

The policies are created in the migration, not here: SQLAlchemy Core has no
vocabulary for them, and inventing one would hide the most security-relevant
part of the schema in a place nobody reviewing security would look.

The complete target schema is specified in ``docs/02-data-model.md``; this
module is the executable half of that document and the two must be kept in
step.

Conventions:

- Primary keys are ULID strings (26 characters) except where an external
  identifier is already canonical and stable, such as an advisory id.
- Timestamps are ``timestamptz``. There are no naive datetimes anywhere.
- Enumerated values are stored as text with a check constraint rather than as a
  Postgres ``enum`` type, because adding a value to a Postgres enum requires a
  migration that cannot run inside a transaction, and these vocabularies grow.
"""

