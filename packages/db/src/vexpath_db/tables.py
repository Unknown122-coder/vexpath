suppressions = Table(
    "suppressions",
    metadata,
    Column("id", String(26), primary_key=True),
    Column("org_id", String(26), ForeignKey("orgs.id", ondelete="CASCADE"), nullable=False),
    Column("project_id", String(26), ForeignKey("projects.id", ondelete="CASCADE"), nullable=False),
    Column("advisory_id", String(64), nullable=False),
    # Null means every component of this project, which is the broader and
    # therefore more dangerous choice, so it is explicit rather than implied.
    Column("purl", Text(), nullable=True),
    # Not nullable on purpose: a suppression nobody explained is one nobody can
    # review, and an unreviewable suppression is how a vulnerability stays
    # hidden after the person who hid it has left.
    Column("reason", Text(), nullable=False),
    Column("justification", String(64), nullable=True),
    # Not nullable either: a suppression without an expiry outlives the
    # situation that justified it.
    Column("expires_at", DateTime(timezone=True), nullable=False),
    Column("created_by", String(26), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    Column("revoked_at", DateTime(timezone=True), nullable=True),
    CheckConstraint("length(trim(reason)) > 0", name="ck_suppressions_reason_not_blank"),
    Index("ix_suppressions_lookup", "project_id", "advisory_id"),
)


