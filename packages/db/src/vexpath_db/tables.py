"""SQLAlchemy Core table definitions.

Only the **global** tables are defined at this milestone: the advisory corpus
and the call-graph cache index. They are world-readable, written only by the
advisory pipeline, and not scoped to a tenant.

Tenant tables arrive in M4 along with row-level security. The complete target
schema is specified in ``docs/02-data-model.md``; this module is the executable
half of that document and the two must be kept in step.

Conventions:

- Primary keys are ULID strings (26 characters) except where an external
  identifier is already canonical and stable, such as an advisory id.
- Timestamps are ``timestamptz``. There are no naive datetimes anywhere.
- Enumerated values are stored as text with a check constraint rather than as a
  Postgres ``enum`` type, because adding a value to a Postgres enum requires a
  migration that cannot run inside a transaction, and these vocabularies grow.
"""

from __future__ import annotations

from enum import StrEnum

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    Column,
    Date,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    MetaData,
    String,
    Table,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB

from vexpath_core.enums import Confidence, SymbolKind, SymbolSource, SymbolsStatus

#: Naming convention so that autogenerated migrations produce stable, readable
#: constraint names instead of database-assigned ones.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)

#: Portable JSON column: JSONB on Postgres, plain JSON elsewhere (SQLite in
#: unit tests), so schema tests do not need a database server.
_Json = JSON().with_variant(JSONB(), "postgresql")
_StringArray = JSON().with_variant(ARRAY(Text()), "postgresql")


def _check(column: str, enum_cls: type[StrEnum], name: str) -> CheckConstraint:
    """Constrain a text column to the values of a Python enum."""
    allowed = ", ".join(f"'{member.value}'" for member in enum_cls)
    return CheckConstraint(f"{column} IN ({allowed})", name=name)


# ---------------------------------------------------------------------------
# Advisory corpus
# ---------------------------------------------------------------------------

advisories = Table(
    "advisories",
    metadata,
    # The canonical identifier, preferring CVE, then GHSA, then the ecosystem's
    # own. Aliases live in the array column, not as separate rows, because an
    # advisory is one fact with several names.
    Column("id", String(64), primary_key=True),
    Column("aliases", _StringArray, nullable=False, default=list),
    Column("summary", Text(), nullable=False, server_default=""),
    Column("details", Text(), nullable=False, server_default=""),
    Column("severity", String(16), nullable=False, server_default="UNKNOWN"),
    Column("cvss_v3", _Json, nullable=True),
    Column("cvss_v4", _Json, nullable=True),
    Column("epss_score", Float(), nullable=True),
    Column("epss_percentile", Float(), nullable=True),
    Column("kev", Boolean(), nullable=False, server_default="false"),
    Column("kev_added_at", Date(), nullable=True),
    Column("cwe_ids", _StringArray, nullable=False, default=list),
    Column("references", _Json, nullable=False, default=list),
    # Upstream repository, the starting point for symbol extraction.
    Column("repo_url", Text(), nullable=True),
    Column("published_at", DateTime(timezone=True), nullable=True),
    Column("modified_at", DateTime(timezone=True), nullable=True),
    Column("withdrawn_at", DateTime(timezone=True), nullable=True),
    # Extraction state of this advisory's vulnerable symbols. The ratio of
    # 'extracted' to everything else is the metric the product's usefulness
    # rests on, so it is a first-class column rather than a derived count.
    Column("symbols_status", String(32), nullable=False, server_default=SymbolsStatus.PENDING),
    Column("source_sha256", String(64), nullable=True),
    Column("synced_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    _check("symbols_status", SymbolsStatus, "symbols_status"),
    # Partial index: KEV advisories are a small, frequently filtered subset.
    Index("ix_advisories_kev", "kev", postgresql_where=text("kev")),
    Index("ix_advisories_symbols_status", "symbols_status"),
    Index("ix_advisories_modified_at", "modified_at"),
)


advisory_affected = Table(
    "advisory_affected",
    metadata,
    Column("id", String(26), primary_key=True),
    Column(
        "advisory_id",
        String(64),
        ForeignKey("advisories.id", ondelete="CASCADE"),
        nullable=False,
    ),
    Column("ecosystem", String(64), nullable=False),
    # Normalised per ecosystem rules (PEP 503 for PyPI, and so on). Matching
    # joins on this, so a non-normalised value here silently loses findings.
    Column("package_name", Text(), nullable=False),
    Column("purl_base", Text(), nullable=False),
    # OSV range events, kept in their original shape. Flattening them to
    # min/max loses advisories whose fix was reverted or backported.
    Column("ranges", _Json, nullable=False, default=list),
    Column("versions", _StringArray, nullable=False, default=list),
    Column("fixed_versions", _StringArray, nullable=False, default=list),
    UniqueConstraint("advisory_id", "ecosystem", "package_name"),
    Index("ix_advisory_affected_lookup", "ecosystem", "package_name"),
    Index("ix_advisory_affected_purl_base", "purl_base"),
)


vulnerable_symbols = Table(
    "vulnerable_symbols",
    metadata,
    Column("id", String(26), primary_key=True),
    Column(
        "advisory_id",
        String(64),
        ForeignKey("advisories.id", ondelete="CASCADE"),
        nullable=False,
    ),
    Column("ecosystem", String(64), nullable=False),
    Column("package_name", Text(), nullable=False),
    # Fully qualified, e.g. requests.adapters.HTTPAdapter.send
    Column("symbol", Text(), nullable=False),
    Column("kind", String(16), nullable=False),
    Column("source", String(32), nullable=False),
    Column("confidence", String(8), nullable=False),
    Column("file_path", Text(), nullable=True),
    Column("fix_commit", String(64), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    UniqueConstraint("advisory_id", "package_name", "symbol"),
    _check("kind", SymbolKind, "kind"),
    _check("source", SymbolSource, "source"),
    _check("confidence", Confidence, "confidence"),
    Index("ix_vulnerable_symbols_lookup", "ecosystem", "package_name"),
)


advisory_snapshots = Table(
    "advisory_snapshots",
    metadata,
    Column("id", String(26), primary_key=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    # Hash over every advisory's source_sha256, sorted. Two snapshots with the
    # same hash are the same corpus, which is what makes a scan reproducible.
    Column("content_sha256", String(64), nullable=False),
    Column("ecosystems", _StringArray, nullable=False, default=list),
    Column("counts", _Json, nullable=False, default=dict),
    UniqueConstraint("content_sha256"),
)


# ---------------------------------------------------------------------------
# Call-graph cache index
# ---------------------------------------------------------------------------

package_callgraphs = Table(
    "package_callgraphs",
    metadata,
    Column("ecosystem", String(64), primary_key=True),
    Column("package_name", Text(), primary_key=True),
    Column("version", String(128), primary_key=True),
    # Bumping the builder version invalidates every cached graph without
    # deleting rows, so a rebuild can be rolled out gradually.
    Column("builder_version", String(32), primary_key=True),
    Column("object_key", Text(), nullable=True),
    Column("node_count", Integer(), nullable=True),
    Column("edge_count", Integer(), nullable=True),
    # Share of call sites the resolver could not bind. Published with results
    # as a quality signal rather than kept private.
    Column("unresolved_call_ratio", Float(), nullable=True),
    Column("status", String(16), nullable=False, server_default="building"),
    Column("error", Text(), nullable=True),
    Column("built_at", DateTime(timezone=True), nullable=True),
    Column("updated_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    CheckConstraint(
        "status IN ('building', 'ready', 'failed')",
        name="ck_package_callgraphs_status",
    ),
    Index("ix_package_callgraphs_status", "status"),
)


#: Tables that hold global, non-tenant data. Tenant tables (M4) will be listed
#: separately so that row-level security can be applied to exactly those.
GLOBAL_TABLES = (
    advisories,
    advisory_affected,
    vulnerable_symbols,
    advisory_snapshots,
    package_callgraphs,
)


