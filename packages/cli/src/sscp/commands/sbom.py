"""The ``sscp sbom`` command group: generate and validate bills of materials."""

from __future__ import annotations

from enum import StrEnum
from pathlib import Path
from typing import Annotated

import typer

from sscp.output import OutputFormat, emit, emit_json, fail, fail_config, note, warn
from sscp_core.sbom import (
    LockfileError,
    UnknownSbomFormatError,
    cyclonedx,
    find_lockfiles,
    generate_sbom,
    load,
    minimum_elements,
    spdx,
)
from sscp_core.sbom.cyclonedx import CycloneDxError
from sscp_core.sbom.spdx import SpdxError

app = typer.Typer(help="Generate and validate software bills of materials.", no_args_is_help=True)


class SbomFormatChoice(StrEnum):
    """Output format for a generated document."""

    CYCLONEDX = "cyclonedx"
    SPDX = "spdx"


@app.command("generate")
def generate(
    path: Annotated[
        Path,
        typer.Argument(exists=True, file_okay=False, help="Project directory to inventory."),
    ] = Path(),
    output: Annotated[
        Path | None,
        typer.Option("--output", "-o", help="Write the document here instead of stdout."),
    ] = None,
    document_format: Annotated[
        SbomFormatChoice,
        typer.Option("--format", "-f", help="Document format to write."),
    ] = SbomFormatChoice.CYCLONEDX,
    lockfile: Annotated[
        Path | None,
        typer.Option(
            "--lockfile",
            exists=True,
            dir_okay=False,
            help="Use this lockfile instead of searching the directory.",
        ),
    ] = None,
) -> None:
    """Generate an SBOM from a project's lockfile.

    The document is deterministic: an unchanged project produces byte-identical
    output, including its serial number, so two runs can be compared.
    """
    try:
        sbom = generate_sbom(path, lockfile=lockfile)
    except LockfileError as exc:
        fail(str(exc))

    gaps = minimum_elements.check(sbom)
    sbom = sbom.model_copy(update={"minimum_element_gaps": gaps})

    text = (
        cyclonedx.to_json(sbom)
        if document_format is SbomFormatChoice.CYCLONEDX
        else spdx.to_json(sbom)
    )

    for item in sbom.notes:
        note(item)

    if output is None:
        emit(text)
    else:
        output.write_text(text, encoding="utf-8", newline="\n")
        note(f"wrote {sbom.component_count} components to {output}")


@app.command("validate")
def validate(
    file: Annotated[
        Path,
        typer.Argument(exists=True, dir_okay=False, help="SBOM document to validate."),
    ],
    output_format: Annotated[
        OutputFormat, typer.Option("--format", "-f", help="Output format.")
    ] = OutputFormat.TABLE,
) -> None:
    """Validate a document and report its minimum-element gaps.

    Schema problems are errors. Minimum-element gaps are reported but do not
    fail the command: an incomplete document is still analysable, and whether
    the gaps matter is the reader's call, not this tool's.
    """
    try:
        sbom = load(file)
    except (UnknownSbomFormatError, CycloneDxError, SpdxError) as exc:
        fail(str(exc))

    gaps = minimum_elements.check(sbom)

    if output_format is OutputFormat.JSON:
        emit_json(
            {
                "file": str(file),
                "format": sbom.format.value,
                "spec_version": sbom.spec_version,
                "valid": True,
                "component_count": sbom.component_count,
                "dependency_edges": len(sbom.edges),
                "generated_by": sbom.generated_by.value,
                "minimum_element_gaps": list(gaps),
                "notes": list(sbom.notes),
            }
        )
        return

    lines = [
        f"{file.name} is a valid {sbom.format.value} document.",
        f"  components       {sbom.component_count}",
        f"  dependency edges {len(sbom.edges)}",
        f"  generated by     {sbom.generated_by.value}",
    ]
    if gaps:
        lines.append("")
        lines.append(f"Minimum-element gaps ({len(gaps)}):")
        lines.extend(f"  - {gap}" for gap in gaps)
    else:
        lines.append("")
        lines.append("No minimum-element gaps.")
    emit("\n".join(lines) + "\n")


@app.command("lockfiles")
def lockfiles(
    path: Annotated[
        Path,
        typer.Argument(exists=True, file_okay=False, help="Project directory to inspect."),
    ] = Path(),
) -> None:
    """List the lockfiles found in a project, best first.

    Useful when a repository holds several and you want to know which one a
    scan would use, before running one.
    """
    found = find_lockfiles(path)
    if not found:
        fail_config(
            f"no supported lockfile in {path}. Generate one with 'uv lock', "
            "'poetry lock' or 'npm install', or pass an SBOM with --sbom."
        )
    lines = [f"Lockfiles in {path}, in the order a scan would prefer them:"]
    for index, candidate in enumerate(found, start=1):
        marker = " (would be used)" if index == 1 else ""
        lines.append(f"  {index}. {candidate.name}{marker}")
    if len(found) > 1:
        warn(
            "More than one lockfile is present. Pass --lockfile to choose "
            "explicitly if the first is not the one that ships."
        )
    emit("\n".join(lines) + "\n")


__all__ = ["app"]
